"""Pro-style icons for all of QGIS through a QGIS UI theme.

The theme (generated by ``scripts/build_icon_theme.py``) is copied to a
themes folder and made active. QGIS 4 only picks up themes from its own
installation folder at start-up (not the profile's themes folder), so that
folder is used when it is writable; otherwise the profile folder is.

QGIS caches icons it has already loaded, so icons currently shown are
swapped directly: an action or button whose icon is the cached QGIS icon of
a theme file gets that file instead. Everything else (dialogs opened later,
and the whole UI after a restart) uses the theme by itself.

Icons QGIS cached from the theme folder (layer icons, Browser items, ...)
cannot be dropped from its cache, but an SVG icon reads its file again when
it is drawn. So disabling the skin writes QGIS's own icons into the theme
folder, and enabling copies the Pro ones back; then everything is redrawn.
"""

import configparser
import os
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from qgis.core import Qgis, QgsApplication, QgsMessageLog, QgsSettings
from qgis.PyQt.QtCore import QFile
from qgis.PyQt.QtGui import QAction, QIcon, QPixmapCache
from qgis.PyQt.QtWidgets import QAbstractButton, QApplication

from .util import tr

THEME = "ArcSkin"
SOURCE = Path(__file__).resolve().parent / "resources" / "qgis_theme"
THEME_KEY = "UI/UITheme"
# UI theme before the skin; kept in settings so that disabling the skin
# after a QGIS restart (when the theme is already ArcSkin) restores it.
ORIGINAL_KEY = "arcskin/original_ui_theme"
DEFAULT_ICONS = ":/images/themes/default"
# Application property: the restart notice was handled in this QGIS session.
NOTICE = "arcskinRestartNotice"
# File in the theme folder: plugin version and icon set ("pro" or "qgis")
# the folder holds, so that ~1000 files are not written again needlessly.
MARKER = "arcskin.version"


# Cache key of each QGIS icon handed out -> its Pro theme file, while the
# skin is on (used for windows opened later, see dialogs.py).
THEMED = {}


def _icon_map(replacement):
    """Cache key of QGIS's cached icon for each theme name -> new file."""
    files = {}
    for path in (SOURCE / "icons").rglob("*.svg"):
        name = path.relative_to(SOURCE / "icons").as_posix()
        new = replacement(name)
        if new:
            files[QgsApplication.getThemeIcon("/" + name).cacheKey()] = new
    return files


def swap_icons(holders, files=None, changes=None):
    """Give actions/buttons whose icon is a known QGIS icon the new file."""
    files = THEMED if files is None else files
    for holder in {id(h): h for h in holders}.values():
        new = files.get(holder.icon().cacheKey())
        if new and changes:
            changes.set(holder, "icon", QIcon(new))
        elif new:
            holder.setIcon(QIcon(new))


def holders_in(widgets, win=None):
    """Actions and buttons of ``widgets`` (and all actions of ``win``)."""
    return ([a for w in widgets for a in w.actions()]
            + (win.findChildren(QAction) if win else [])
            + [w for w in widgets if isinstance(w, QAbstractButton)])


def _swap_loaded_icons(win, replacement, changes=None):
    """Replace in-use QGIS theme icons on actions and buttons."""
    files = _icon_map(replacement)
    swap_icons(holders_in(QApplication.allWidgets(), win), files, changes)
    return files


def _write(files):
    """Write {path: bytes}; in parallel, as writing ~1000 small files to
    the QGIS install folder is slow (virus scanning). A file that cannot
    be written (locked, no permission) is logged and skipped: its icon
    then keeps the look of whatever is in the file."""
    def write(item):
        path, data = item
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        except OSError:
            return path
    with ThreadPoolExecutor(8) as pool:
        failed = [path for path in pool.map(write, files.items()) if path]
    if failed:
        QgsMessageLog.logMessage(
            tr("{} icon files could not be written, e.g. {}").format(
                len(failed), failed[0]),
            "ArcSkin", Qgis.MessageLevel.Warning)
    return not failed


def _version():
    cfg = configparser.ConfigParser()
    cfg.read(Path(__file__).resolve().parent / "metadata.txt",
             encoding="utf-8")
    return cfg["general"]["version"]


def _marked(target, icons):
    """Whether ``target`` holds this version's ``icons`` ("pro"/"qgis")."""
    try:
        return (target / MARKER).read_text() == f"{_version()} {icons}"
    except OSError:
        return False


def _mark(target, icons):
    """Record in ``target`` which icon set it holds (if it can be written)."""
    try:
        (target / MARKER).write_text(f"{_version()} {icons}")
    except OSError:
        pass


def _write_qgis_icons(target):
    """Overwrite the theme folder's icons with QGIS's own ones."""
    files = {}
    for path in (target / "icons").rglob("*.svg"):
        name = path.relative_to(target / "icons").as_posix()
        default = QFile(f"{DEFAULT_ICONS}/{name}")
        if default.open(QFile.OpenModeFlag.ReadOnly):
            files[path] = bytes(default.readAll())
            default.close()
    if _write(files):
        _mark(target, "qgis")


def _redraw():
    """Draw all icons again from their files."""
    QPixmapCache.clear()
    for widget in QApplication.allWidgets():
        widget.update()


def install_icon_theme():
    """Copy the theme to a themes folder QGIS reads and select it."""
    folder = Path(QgsApplication.defaultThemesFolder())
    if not os.access(folder, os.W_OK):
        folder = Path(QgsApplication.userThemesFolder())
    target = folder / THEME
    if not _marked(target, "pro") and _write(
            {target / path.relative_to(SOURCE): path.read_bytes()
             for path in SOURCE.rglob("*") if path.is_file()}):
        _mark(target, "pro")
    QgsSettings().setValue(THEME_KEY, THEME)
    return target


def apply_icon_theme(iface, changes):
    """Install and activate the icon theme; undone on disable."""
    settings = QgsSettings()
    previous_setting = settings.value(THEME_KEY)
    if settings.value(ORIGINAL_KEY) is None:
        settings.setValue(ORIGINAL_KEY, previous_setting
                          if previous_setting not in (None, THEME)
                          else "default")
    target = install_icon_theme()
    QgsApplication.setThemeName(THEME)
    win = iface.mainWindow()

    def undo():
        # Runs after the swaps below are undone. Icons QGIS cached from the
        # theme folder keep reading it, so it gets QGIS's own icons.
        original = settings.value(ORIGINAL_KEY, "default")
        QgsApplication.setThemeName(original)
        settings.setValue(THEME_KEY, original)
        settings.remove(ORIGINAL_KEY)
        THEMED.clear()
        _write_qgis_icons(target)
        _redraw()

    changes.add(undo)
    _redraw()  # icons cached from the folder are Pro again
    THEMED.update(_swap_loaded_icons(
        win, lambda name: str(target / "icons" / name)
        if (target / "icons" / name).exists() else None, changes))
    # Icons QGIS cached from its own resources before the theme was active
    # (layer icons in Contents and Catalog) only change after a restart:
    # say so once, when QGIS started with another theme.
    app = QApplication.instance()
    if not app.property(NOTICE):
        app.setProperty(NOTICE, True)
        if previous_setting != THEME:
            iface.messageBar().pushMessage(
                "ArcSkin", tr("Layer icons in Contents and Catalog change "
                              "after restarting QGIS."),
                Qgis.MessageLevel.Info, 10)
